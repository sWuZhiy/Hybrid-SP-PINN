"""单位换算工具。

内部计算统一使用 SI 单位；本模块提供 SI 与常用半导体单位之间的换算。
所有换算常数集中定义于此，业务代码禁止散落魔法数字。
"""

from .constants import q

# ---------------------------------------------------------------------------
# 能量：电子伏特 (eV) 与 焦耳 (J)
# ---------------------------------------------------------------------------
EV_TO_J = q          # 1 eV = q 焦耳（严格成立）
J_TO_EV = 1.0 / q    # 1 J = (1/q) 电子伏特

# ---------------------------------------------------------------------------
# 长度：纳米 (nm) 与 米 (m)
# ---------------------------------------------------------------------------
NM_TO_M = 1e-9
M_TO_NM = 1e9

# ---------------------------------------------------------------------------
# 浓度：cm^-3 与 m^-3
# ---------------------------------------------------------------------------
CM3_TO_M3 = 1e6      # 1 cm^-3 = 1e6 m^-3
M3_TO_CM3 = 1e-6     # 1 m^-3 = 1e-6 cm^-3


# ---------------------------------------------------------------------------
# 换算函数
# ---------------------------------------------------------------------------
def ev_to_joule(value):
    """电子伏特 → 焦耳。"""
    return value * EV_TO_J


def joule_to_ev(value):
    """焦耳 → 电子伏特。"""
    return value * J_TO_EV


def nm_to_m(value):
    """纳米 → 米。"""
    return value * NM_TO_M


def m_to_nm(value):
    """米 → 纳米。"""
    return value * M_TO_NM


def cm3_to_m3(value):
    """cm^-3 → m^-3。"""
    return value * CM3_TO_M3


def m3_to_cm3(value):
    """m^-3 → cm^-3。"""
    return value * M3_TO_CM3
